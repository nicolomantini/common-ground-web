const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context = vm.createContext({URL, location:{href:'https://common-ground.space/'}, document:{getElementById:()=>({})}});
vm.runInContext(fs.readFileSync('js/booking-link.js','utf8'),context);
vm.runInContext(fs.readFileSync('js/app.js','utf8').split('function render() {')[0],context);
const hostile = '"><img src=x onerror=alert(1)>';
context.profile = Object.fromEntries(['id','name','pronouns','bio','location','price_range','availability','session_length'].map(k=>[k,hostile]));
Object.assign(context.profile,{specialties:[hostile],formats:[hostile],approach:[hostile],languages:[hostile],photo:'javascript:alert(1)',whatsapp:hostile});
const html = vm.runInContext('cardHTML(profile)',context);
assert.ok(!html.includes('<img src=x'));
assert.ok(!html.includes('src="javascript:'));
assert.ok(!html.includes('https://wa.me/'));
assert.ok(html.includes('&lt;img'));
vm.runInContext('allSpecialties = [profile.name]; buildChips()',context);
assert.ok(!vm.runInContext('chipRow.innerHTML',context).includes('<img src=x'));
vm.runInContext('REVIEWS_BY_COUNSELOR[profile.id] = {items:[{rating:5,name:profile.name,comment:profile.name}]};',context);
assert.ok(!vm.runInContext('reviewsDetailHTML(profile)',context).includes('<img src=x'));
assert.equal(vm.runInContext('whatsappNumber("+41 (79) 123-45-67")',context),'41791234567');
assert.equal(vm.runInContext('safeProfilePhoto("images/logo.png")',context),'https://common-ground.space/images/logo.png');
assert.equal(vm.runInContext('safeProfilePhoto("data:text/html,hello")',context),null);
context.profile={id:'person',name:'Anne & Luisa',specialties:['Inquiry'],photo:'https://example.com/photo.png',whatsapp:'+41791234567'};
const normal=vm.runInContext('cardHTML(profile)',context);
assert.ok(normal.includes('Anne &amp; Luisa'));
assert.ok(normal.includes('https://wa.me/41791234567'));
assert.ok(normal.includes('src="https://example.com/photo.png"'));
console.log('Profile rendering handles hostile content and normal profile links.');
